// ========================================
// DOM ELEMENTS
// ========================================

const portfolioView =
  document.getElementById("portfolio-view");

const projectView =
  document.getElementById("project-view");

const projectsGrid =
  document.getElementById("projects-grid");

const backButton =
  document.getElementById("back-button");

const runButton =
  document.getElementById("run-button");

const executionStatus =
  document.getElementById("execution-status");

// ========================================
// MODAL ELEMENTS
// ========================================

const resultsModal =
  document.getElementById("results-modal");

const modalContainer =
  document.querySelector(".modal-container");

const modalTitle =
  document.getElementById("modal-title");

const resultsDescription =
  document.getElementById("results-description");

const resultsContainer =
  document.getElementById("results-container");

const closeModalButton =
  document.getElementById("close-modal");

const modalDoneButton =
  document.getElementById("modal-done");

// ========================================
// APPLICATION STATE
// ========================================

let currentProject = null;

let executionTimer = null;

let previousFocusedElement = null;

// ========================================
// HELPERS
// ========================================

function createElement(tag, className, text) {

  const element = document.createElement(tag);

  if (className) {
    element.className = className;
  }

  if (text !== undefined) {
    element.textContent = text;
  }

  return element;
}

// ========================================
// RENDER PORTFOLIO
// ========================================

function renderPortfolio() {

  projectsGrid.replaceChildren();

  projects.forEach(project => {

    const card =
      createElement("article", "project-card");

    // Header

    const cardTop =
      createElement("div", "card-top");

    cardTop.append(
      createElement(
        "span",
        "card-number",
        project.number
      ),
      createElement(
        "span",
        "card-category",
        project.category
      )
    );

    card.appendChild(cardTop);

    // Icon

    card.appendChild(
      createElement(
        "div",
        `card-icon ${project.iconClass}`,
        project.icon
      )
    );

    // Title

    card.appendChild(
      createElement(
        "h3",
        "",
        project.title
      )
    );

    // Description

    card.appendChild(
      createElement(
        "p",
        "card-description",
        project.shortDescription
      )
    );

    // Technologies

    card.appendChild(
      createElement(
        "div",
        "card-technologies",
        project.technologies.join(" · ")
      )
    );

    // Button

    const button =
      createElement(
        "button",
        "card-button"
      );

    button.type = "button";

    button.append(
      createElement(
        "span",
        "",
        "Explore Project"
      ),
      createElement(
        "span",
        "",
        "↗"
      )
    );

    button.addEventListener("click", () => {
      window.location.hash = project.id;
    });

    card.appendChild(button);

    projectsGrid.appendChild(card);

  });

}

// ========================================
// MODAL MANAGEMENT
// ========================================

function openResultsModal(project) {

  previousFocusedElement = document.activeElement;

  // Dynamic title

  modalTitle.textContent =
    project.title;

  // Dynamic description

  const resultCount = project.results.length;

  resultsDescription.textContent =
    `${resultCount} precomputed ${resultCount === 1 ? "result" : "results"} generated by the original Python implementation.`;

  // Show modal

  resultsModal.hidden = false;

  document.body.classList.add("modal-open");

  // Focus close button

  closeModalButton.focus();

}

// ========================================
// CLOSE MODAL
// ========================================

function closeResultsModal() {

  if (resultsModal.hidden) {
    return;
  }

  resultsModal.hidden = true;

  document.body.classList.remove("modal-open");

  // Restore focus

  if (
    previousFocusedElement instanceof HTMLElement &&
    previousFocusedElement.isConnected
  ) {
    previousFocusedElement.focus();
  }

  previousFocusedElement = null;

}

// ========================================
// RESET EXECUTION
// ========================================

function resetExecution() {

  // Cancel pending execution

  if (executionTimer !== null) {

    clearTimeout(executionTimer);

    executionTimer = null;

  }

  // Reset button

  runButton.disabled = false;

  runButton.textContent = "▶ Run Analysis";

  // Clear status

  executionStatus.textContent = "";

  // Close modal if necessary

  closeResultsModal();

  // Remove previous results

  resultsContainer.replaceChildren();

}

// ========================================
// SHOW PROJECT
// ========================================

function showProject(project) {

  resetExecution();

  currentProject = project;

  portfolioView.hidden = true;

  projectView.hidden = false;

  // Project number

  document.getElementById(
    "project-number"
  ).textContent = `PROJECT ${project.number}`;

  // Category

  document.getElementById(
    "project-category"
  ).textContent = project.category;

  // Title

  document.getElementById(
    "project-title"
  ).textContent = project.title;

  // Description

  document.getElementById(
    "project-description"
  ).textContent = project.description;

  // Technologies

  const technologiesContainer =
    document.getElementById("project-technologies");

  technologiesContainer.replaceChildren();

  project.technologies.forEach(technology => {

    technologiesContainer.appendChild(
      createElement(
        "span",
        "",
        technology
      )
    );

  });

  // Python source

  const sourceLink =
    document.getElementById("source-link");

  sourceLink.href =
    `${GITHUB_BASE}${project.id}/${project.sourceFile}`;

  window.scrollTo(0, 0);

}

// ========================================
// SHOW PORTFOLIO
// ========================================

function showPortfolio() {

  resetExecution();

  currentProject = null;

  projectView.hidden = true;

  portfolioView.hidden = false;

  window.scrollTo(0, 0);

}

// ========================================
// ROUTING
// ========================================

function handleRoute() {

  const projectId =
    decodeURIComponent(
      window.location.hash.substring(1)
    );

  const project =
    projects.find(
      item => item.id === projectId
    );

  if (project) {

    showProject(project);

  } else {

    showPortfolio();

  }

}

// ========================================
// DISPLAY RESULTS
// ========================================

function displayResults(project) {

  if (currentProject !== project) {
    return;
  }

  // Clear previous results

  resultsContainer.replaceChildren();

  // Create result cards

  project.results.forEach(result => {

    const card =
      createElement(
        "article",
        "result-card"
      );

    if (project.results.length === 1) {
      card.classList.add("full-width");
    }

    // Result title

    card.appendChild(
      createElement(
        "h3",
        "",
        result.title
      )
    );

    // Result description

    card.appendChild(
      createElement(
        "p",
        "result-description",
        result.description
      )
    );

    // Original Python-generated image

    const image =
      createElement(
        "img",
        "result-image"
      );

    image.src =
      `./${project.id}/${result.image}`;

    image.alt =
      `${result.title} — Original Python analysis output`;

    image.loading = "eager";

    // Handle missing images

    image.addEventListener(
      "error",
      function () {

        const error =
          createElement(
            "p",
            "image-error",
            `Unable to load ${result.image}. Verify that the original image exists in the project directory.`
          );

        image.replaceWith(error);

      },
      { once: true }
    );

    card.appendChild(image);

    resultsContainer.appendChild(card);

  });

  // Update execution status

  executionStatus.textContent =
    "✓ Precomputed results loaded successfully";

  runButton.disabled = false;

  runButton.textContent =
    "↻ Run Analysis Again";

  executionTimer = null;

  // Automatically open modal

  openResultsModal(project);

}

// ========================================
// SIMULATE EXECUTION
// ========================================

function runAnalysis() {

  if (!currentProject || runButton.disabled) {
    return;
  }

  const project = currentProject;

  // Reset previous execution

  resetExecution();

  // Processing state

  runButton.disabled = true;

  runButton.textContent =
    "Processing Analysis...";

  executionStatus.textContent =
    "Preparing Python analysis results...";

  // Simulated processing delay.
  // Python is not executed in the browser.

  executionTimer = setTimeout(() => {

    displayResults(project);

  }, 900);

}

// ========================================
// MODAL EVENTS
// ========================================

// Close button

closeModalButton.addEventListener(
  "click",
  closeResultsModal
);

// Done button

modalDoneButton.addEventListener(
  "click",
  closeResultsModal
);

// Click outside modal

resultsModal.addEventListener(
  "click",
  function (event) {

    if (event.target === resultsModal) {
      closeResultsModal();
    }

  }
);

// Keyboard events

document.addEventListener(
  "keydown",
  function (event) {

    if (resultsModal.hidden) {
      return;
    }

    // ESC closes modal

    if (event.key === "Escape") {

      event.preventDefault();

      closeResultsModal();

      return;
    }

    // Keep focus inside modal

    if (event.key === "Tab") {

      const focusableElements = [
        closeModalButton,
        modalDoneButton
      ];

      const firstElement = focusableElements[0];

      const lastElement =
        focusableElements[focusableElements.length - 1];

      if (event.shiftKey) {

        if (
          document.activeElement === firstElement ||
          document.activeElement === modalContainer
        ) {

          event.preventDefault();

          lastElement.focus();

        }

      } else {

        if (document.activeElement === lastElement) {

          event.preventDefault();

          firstElement.focus();

        }

      }

    }

  }
);

// ========================================
// APPLICATION EVENTS
// ========================================

runButton.addEventListener(
  "click",
  runAnalysis
);

backButton.addEventListener(
  "click",
  function () {

    window.location.hash = "";

  }
);

window.addEventListener(
  "hashchange",
  handleRoute
);

// ========================================
// INITIALIZATION
// ========================================

renderPortfolio();

handleRoute();

console.log(
  "Data Analysis Portfolio initialized successfully"
);